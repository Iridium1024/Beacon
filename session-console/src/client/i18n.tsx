interface ConsoleI18nValue {
  locale: ConsoleLocale;
  t: (key: ConsoleCopyKey) => string;
}

const defaultValue: ConsoleI18nValue = {
  locale: "en-US",
  t: (key) => EN[key],
};

const ConsoleI18nContext = createContext<ConsoleI18nValue>(defaultValue);

export function ConsoleI18nProvider({
  children,
  locale,
}: {
  children: ReactNode;
  locale: ConsoleLocale;
}): JSX.Element {
  const value = useMemo<ConsoleI18nValue>(() => ({
    locale,
    t: (key) => (locale === "zh-CN" ? ZH : EN)[key],
  }), [locale]);
  return <ConsoleI18nContext.Provider value={value}>{children}</ConsoleI18nContext.Provider>;
}

export const useConsoleI18n = (): ConsoleI18nValue => useContext(ConsoleI18nContext);
