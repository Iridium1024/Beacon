"""Operational coordination ports, independent of CLI and storage technology."""
from typing import Protocol


class RuntimeCoordination(Protocol):
    def enabled(self) -> bool: ...
    def require_owner(self, token: dict, now: str, *, allow_draining: bool = False) -> dict: ...
    def consumer_status(self, workspace_id: str, now: str) -> dict: ...
    def acquire(self, workspace_id: str, *, pid: int, start_id: str, now: str, ttl: float) -> dict: ...
    def heartbeat(self, token: dict, *, now: str, ttl: float, draining: bool = False) -> dict: ...
    def finish(self, token: dict, now: str) -> None: ...
    def request_stop(self, workspace_id: str, now: str) -> dict: ...
    def cleanup(self, now: str, *, limit: int = 100) -> int: ...
    def notice(self, workspace_id: str, deliveries: list[dict], now: str) -> None: ...
    def intent(self, workspace_id: str, session_key: str) -> dict | None: ...
    def drain_intent(self, token: dict, session_key: str, version: int, *, now: str, delay: float) -> bool: ...
    def register_activation(self, token: dict, claim: dict, *, nonce: str, now: str) -> None: ...
    def attach_process(self, token: dict, attempt_id: str, *, pid: int, start_id: str, now: str) -> None: ...
    def stage_evidence(self, workspace_id: str, attempt_id: str, nonce: str, evidence: dict, now: str) -> None: ...
    def staged(self, workspace_id: str, attempt_id: str) -> dict | None: ...
    def waiter_open(self, observation: dict, *, now: str, ttl: float) -> dict: ...
    def waiter_renew(self, token: dict, *, now: str, ttl: float) -> None: ...
    def waiter_close(self, token: dict, now: str) -> None: ...
    def waiters(self, workspace_id: str, message_id: str, now: str) -> list[dict]: ...
    def waiter_candidates(self, workspace_id: str, message_id: str, *, limit: int = 101) -> list[dict]: ...


class ActivationProcessPort(Protocol):
    def start(self, claim: dict, consumer: dict, nonce: str): ...
    def poll(self, child) -> int | None: ...
    def stop(self, child) -> None: ...
    def close(self, child) -> None: ...
